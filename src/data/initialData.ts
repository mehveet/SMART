export const calculateRedistributionSummary = (
  surplusBatches: SurplusBatch[],
  dispatches: RedistributionDispatch[]
): RedistributionSummaryData => {
  const availableKg = Number(
    surplusBatches
      .filter(b => b.status === 'Available' || (!b.status && b.redistributionStatus === 'staged'))
      .reduce((sum, b) => sum + (b.weightKg || b.quantity || 0), 0)
      .toFixed(1)
  );

  const matchedKg = Number(
    surplusBatches
      .filter(
        b =>
          b.status === 'Matched' ||
          b.status === 'Pickup Scheduled' ||
          (!b.status && b.redistributionStatus === 'allocated')
      )
      .reduce((sum, b) => sum + (b.weightKg || b.quantity || 0), 0)
      .toFixed(1)
  );

  const collectedKg = Number(
    surplusBatches
      .filter(b => b.status === 'Collected' || (!b.status && b.redistributionStatus === 'dispatched'))
      .reduce((sum, b) => sum + (b.weightKg || b.quantity || 0), 0)
      .toFixed(1)
  );

  const deliveredKg = Number(
    surplusBatches
      .filter(b => b.status === 'Delivered' || (!b.status && b.redistributionStatus === 'completed'))
      .reduce((sum, b) => sum + (b.weightKg || b.quantity || 0), 0)
      .toFixed(1)
  );

  const totalKg = Number((availableKg + matchedKg + collectedKg + deliveredKg).toFixed(1));
  const recoveryRatePercent =
    totalKg > 0 ? Number(((deliveredKg / totalKg) * 100).toFixed(1)) : 94.2;

  return {
    availableKg,
    matchedKg,
    collectedKg,
    deliveredKg,
    totalKg,
    recoveryRatePercent,
  };
};

