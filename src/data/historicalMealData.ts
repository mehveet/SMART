// Helper to generate CSV string for download or testing
export const generateCSVFromRecords = (records: HistoricalMealRecord[]): string => {
  const headers = [
    'date',
    'dayOfWeek',
    'mealCategory',
    'menuName',
    'attendance',
    'mealsPrepared',
    'mealsServed',
    'surplusMeals',
    'wasteKg',
    'specialEvent',
    'weather',
  ];

  const rows = records.map(r => [
    r.date,
    r.dayOfWeek,
    r.mealCategory,
    `"${r.menuName || ''}"`,
    r.attendance,
    r.mealsPrepared,
    r.mealsServed,
    r.surplusMeals,
    r.wasteKg,
    r.specialEvent,
    r.weather,
  ]);

  return [headers.join(','), ...rows.map(row => row.join(','))].join('\n');
};

